#!/usr/bin/env python3
"""
ALL SEEING EYES skill registry tool.

One folder per skill under registry/<skill>/:
  skill.json                    version + drift metadata (source of truth)
  platforms/<platform>/...      that platform's version of the skill

Commands:
  status            rebuild STATUS.md, index.json, Claude Code plugin mirror
  status --check    same, but exit 1 if any platform file changed without a version bump
  bump <skill> <platform> [--note TEXT] [--canonical] [--minor|--major]
                    record a new version of one platform's copy
  import <skill> <platform> <src_dir> [--note TEXT] [--canonical]
                    copy a folder in as that platform's version, then bump
"""
import argparse
import datetime as dt
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REG = ROOT / "registry"
DIST = ROOT / "dist" / "claude"
MARKET = ROOT / ".claude-plugin" / "marketplace.json"
PLUGIN_NAME = "all-seeing-eyes"

PLATFORMS = {
    "claude": {"label": "Claude", "entry": "SKILL.md",
               "install": "Claude.ai: upload the .skill zip. Claude Code: /plugin install all-seeing-eyes@anthropic-agent-skills"},
    "gemini": {"label": "Gemini", "entry": "GEM.md",
               "install": "Gemini: paste into a Gem's Instructions field"},
    "grok": {"label": "Grok", "entry": "PROJECT.md",
             "install": "Grok: paste into a Project's custom instructions"},
    "perplexity": {"label": "Perplexity", "entry": "SPACE.md",
                   "install": "Perplexity: paste into a Space's instructions"},
}


def today():
    return dt.date.today().isoformat()


def vtuple(v):
    nums = [int(x) for x in re.findall(r"\d+", v or "")][:3]
    return tuple(nums + [0] * (3 - len(nums)))


def bump_version(v, part="patch"):
    major, minor, patch = vtuple(v)
    if part == "major":
        return f"{major + 1}.0.0"
    if part == "minor":
        return f"{major}.{minor + 1}.0"
    return f"{major}.{minor}.{patch + 1}"


def dir_hash(path: Path):
    if not path.exists():
        return None
    h = hashlib.sha256()
    for f in sorted(p for p in path.rglob("*") if p.is_file()):
        h.update(str(f.relative_to(path)).encode())
        h.update(f.read_bytes())
    return h.hexdigest()[:12]


def load(skill_dir: Path):
    return json.loads((skill_dir / "skill.json").read_text())


def save(skill_dir: Path, data):
    (skill_dir / "skill.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def frontmatter(md: Path):
    out = {}
    if not md.exists():
        return out
    text = md.read_text()
    m = re.match(r"^---\n(.*?)\n---", text, re.S)
    if not m:
        return out
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def skills():
    if not REG.exists():
        return []
    return sorted(d for d in REG.iterdir() if d.is_dir() and (d / "skill.json").exists())


def platform_state(skill_dir, data, p):
    meta = data["platforms"].get(p, {})
    pdir = skill_dir / "platforms" / p
    actual = dir_hash(pdir)
    canon = data["canonical"]["version"]
    if actual is None:
        return "missing", meta
    if meta.get("hash") and meta["hash"] != actual:
        return "unversioned-edit", meta
    if vtuple(meta.get("version")) < vtuple(canon):
        return "behind", meta
    return "current", meta


ICON = {"current": "🟢 current", "behind": "🟠 behind", "missing": "⚪ missing",
        "unversioned-edit": "🔴 edited, not bumped"}


def cmd_status(check=False):
    rows, index, problems = [], [], []
    for sd in skills():
        data = load(sd)
        entry = {"name": data["name"], "summary": data.get("summary", ""),
                 "canonical": data["canonical"], "platforms": {}}
        cells = []
        for p in PLATFORMS:
            state, meta = platform_state(sd, data, p)
            entry["platforms"][p] = {"state": state, "version": meta.get("version"), "updated": meta.get("updated")}
            v = f" v{meta['version']}" if meta.get("version") and state != "missing" else ""
            cells.append(f"{ICON[state]}{v}")
            if state == "unversioned-edit":
                problems.append(f"{data['name']}/{p}: files changed without a version bump")
        index.append(entry)
        c = data["canonical"]
        rows.append(f"| [{data['name']}](registry/{sd.name}/) | v{c['version']} ({PLATFORMS[c['platform']]['label']}, {c['updated']}) | " + " | ".join(cells) + " |")

    behind = [(e["name"], p) for e in index for p, s in e["platforms"].items() if s["state"] in ("behind", "missing")]
    lines = [
        "# Skill Registry Status",
        "",
        "Generated by `tools/registry.py`. Do not edit by hand.",
        "",
        f"Skills tracked: {len(index)}  |  Platform copies needing work: {len(behind)}",
        "",
        "| Skill | Canonical | " + " | ".join(PLATFORMS[p]["label"] for p in PLATFORMS) + " |",
        "|---|---|" + "---|" * len(PLATFORMS),
        *rows,
        "",
        "## Port queue",
        "",
    ]
    if behind:
        lines += [f"- `{n}` to {PLATFORMS[p]['label']}" for n, p in behind]
    else:
        lines.append("Nothing to port. Every platform is current.")
    lines += ["", "## Legend", "",
              "- 🟢 current: matches the canonical version",
              "- 🟠 behind: older than canonical, needs a port",
              "- ⚪ missing: no copy for that platform yet",
              "- 🔴 edited, not bumped: files changed but `skill.json` was not updated", ""]
    (REG / "STATUS.md").write_text("\n".join(lines))
    (REG / "index.json").write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n")
    build_claude_mirror()

    if problems:
        print("\n".join(problems), file=sys.stderr)
        if check:
            sys.exit(1)
    print(f"OK: {len(index)} skills, {len(behind)} platform copies need work")


def build_claude_mirror():
    """Mirror every Claude copy into dist/claude/<skill>/ and register it as a Claude Code plugin."""
    if DIST.exists():
        shutil.rmtree(DIST)
    names = []
    for sd in skills():
        src = sd / "platforms" / "claude"
        if (src / "SKILL.md").exists():
            shutil.copytree(src, DIST / sd.name)
            names.append(sd.name)
    if not MARKET.exists():
        return
    m = json.loads(MARKET.read_text())
    m["plugins"] = [p for p in m["plugins"] if p["name"] != PLUGIN_NAME]
    m["plugins"].append({
        "name": PLUGIN_NAME,
        "description": "ALL SEEING EYES (@allsxxingeyes) custom skills, auto-built from registry/",
        "source": "./",
        "strict": False,
        "skills": [f"./dist/claude/{n}" for n in names],
    })
    MARKET.write_text(json.dumps(m, indent=2, ensure_ascii=False) + "\n")


def cmd_bump(skill, platform, note, canonical, part, force_version=None):
    sd = REG / skill
    if platform not in PLATFORMS:
        sys.exit(f"Unknown platform {platform}. Use one of: {', '.join(PLATFORMS)}")
    data = load(sd)
    pdir = sd / "platforms" / platform
    if not pdir.exists():
        sys.exit(f"No files at {pdir}")
    meta = data["platforms"].get(platform, {})
    base = max(vtuple(meta.get("version")), vtuple(data["canonical"]["version"])) if canonical else vtuple(meta.get("version"))
    if force_version:
        new_v = ".".join(map(str, vtuple(force_version)))
    elif meta.get("version") or (canonical and data["canonical"]["version"] != "0.0.0"):
        new_v = bump_version(".".join(map(str, base)), part)
    else:
        new_v = "1.0.0"
    data["platforms"][platform] = {"version": new_v, "updated": today(), "hash": dir_hash(pdir),
                                   "entry": PLATFORMS[platform]["entry"]}
    if canonical or vtuple(new_v) > vtuple(data["canonical"]["version"]):
        data["canonical"] = {"platform": platform, "version": new_v, "updated": today()}
    data.setdefault("changelog", []).insert(0, {"version": new_v, "date": today(), "platform": platform,
                                                "note": note or "Updated"})
    save(sd, data)
    print(f"{skill}/{platform} -> v{new_v} (canonical: {data['canonical']['platform']} v{data['canonical']['version']})")


def cmd_import(skill, platform, src, note, canonical, version=None):
    sd = REG / skill
    pdir = sd / "platforms" / platform
    if pdir.exists():
        shutil.rmtree(pdir)
    shutil.copytree(src, pdir)
    if not (sd / "skill.json").exists():
        fm = frontmatter(pdir / PLATFORMS[platform]["entry"])
        save(sd, {"name": skill, "summary": fm.get("description", ""),
                  "canonical": {"platform": platform, "version": "0.0.0", "updated": today()},
                  "platforms": {}, "changelog": []})
    cmd_bump(skill, platform, note, canonical, "patch", version)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("status"); s.add_argument("--check", action="store_true")
    b = sub.add_parser("bump"); b.add_argument("skill"); b.add_argument("platform")
    b.add_argument("--note"); b.add_argument("--canonical", action="store_true")
    g = b.add_mutually_exclusive_group(); g.add_argument("--minor", action="store_true"); g.add_argument("--major", action="store_true")
    i = sub.add_parser("import"); i.add_argument("skill"); i.add_argument("platform"); i.add_argument("src")
    i.add_argument("--note"); i.add_argument("--canonical", action="store_true"); i.add_argument("--version")
    a = ap.parse_args()
    if a.cmd == "status":
        cmd_status(a.check)
    elif a.cmd == "bump":
        cmd_bump(a.skill, a.platform, a.note, a.canonical, "major" if a.major else "minor" if a.minor else "patch")
    elif a.cmd == "import":
        cmd_import(a.skill, a.platform, a.src, a.note, a.canonical, a.version)


if __name__ == "__main__":
    main()
